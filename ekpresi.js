
const convertCelciusToFarenheit = function(temp){
const result = (9/5) * temp + 32;
return result;
}

//convertCelciusToFarenheit = identifier atau nama fungsi 
//function = keyword function
//(temp) = parameter
//{} = function body atau isi function
console.info("Contoh Ekspretion Function");
console.log(convertCelciusToFarenheit(20)); 


