//operator tambahan (+)
var a = 5;
var b = 10;
var jumlah = a + b;
console.info("Operator Tambahan (+):");
console.log(jumlah);

//operator pengurangan (-)
var c = 15;
var d = 5;
var selisih = c - d;
console.info("Operator Pengurangan (-):");  
console.log(selisih);

//operator perkalian (*)
var e = 4;
var f = 6;
var Kali = e * f;
console.info("Operator Perkalian (*):");
console.log(Kali);

//operator pembagian (/)
var g = 20;
var h = 4;
var Bagi = g / h;
console.info("Operator Pembagian (/):");
console.log(Bagi);

//operator modulus (%)
var i = 15;
var j = 4;
var Modulus = i % j;
console.info("Operator Modulus (%):");
console.log(Modulus);

//operator kurung ()
var k = 4;
var l = 5;
var m = 6;
var hasil = k + (l - m);
var hasil2 = 10 + (2-5) * 2;
var nilai3 = 5 % 2 + (3 + 5) * 2 * 4;
console.info("Operator Kurung ():");
console.log(hasil);
console.log(hasil2);
console.log(nilai3);


